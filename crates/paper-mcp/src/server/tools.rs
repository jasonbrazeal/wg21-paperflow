//! The MCP tools and their parameter and result types.
//!
//! Every read tool reads paperstore directly and resolves an unversioned
//! paper id to its latest stored revision. Unknown papers, malformed ids,
//! invalid line ranges and mismatched revisions come back as MCP tool
//! errors carrying the error message.
//!
//! The search tools query the index. A call without a cursor runs the
//! search, stores the full ranked list in the server's cursor cache and
//! returns its first page; a call with a cursor returns the next page of
//! that stored list without searching again, ignoring its other
//! parameters. An expired, unknown or other tool's cursor is a tool error.

// The `ServerHandler` impl generated by `tool_router(server_handler)` has
// async methods that never await, and an allow on the impl block does not
// reach it.
#![allow(clippy::unused_async_trait_impl)]

