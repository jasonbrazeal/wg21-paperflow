/// Lines of unchanged context around each change in a diff.
const DIFF_CONTEXT_LINES: usize = 3;

/// Names one paper.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct PaperIdParams {
    /// Paper id such as `P2300R10`, or `P2300` for the latest revision.
    pub paper_id: String,
}

/// Names a paper and a range of its lines.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct PaperLinesParams {
    /// Paper id such as `P2300R10`, or `P2300` for the latest revision.
    pub paper_id: String,
    /// First line, 1-based and inclusive; negative counts from the end
    /// (`-1` is the last line). Defaults to the first line. Never 0.
    #[serde(default)]
    pub start: Option<i64>,
    /// Line after the range, 1-based and exclusive; negative counts from the
    /// end. Defaults to past the last line. At least one bound is required.
    #[serde(default)]
    pub end: Option<i64>,
}

/// Names two revisions of one paper.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct DiffParams {
    /// The older revision, such as `P2300R9`.
    pub from_id: String,
    /// The newer revision, such as `P2300R10`, or `P2300` for the latest.
    pub to_id: String,
}

/// A range of a paper's lines.
#[derive(Debug, Serialize, JsonSchema)]
pub struct PaperLines {
    /// The resolved paper id.
    pub paper_id: String,
    /// First returned line, 1-based and inclusive.
    pub start: usize,
    /// Line after the last returned line, 1-based and exclusive.
    pub end: usize,
    /// Number of lines in the whole paper.
    pub total_lines: usize,
    /// The lines, joined with `\n`.
    pub text: String,
}

/// Every paperstore metadata field of one paper.
#[derive(Clone, Debug, Serialize, JsonSchema)]
pub struct PaperMetadata {
    /// The resolved paper id.
    pub paper_id: String,
    /// Mailing year.
    pub year: String,
    /// Paper title.
    pub title: String,
    /// Author names.
    pub authors: Vec<String>,
    /// Target subgroup.
    pub target_group: String,
    /// Intent signal from conversion.
    pub intent: String,
    /// Canonical URL.
    pub url: String,
    /// Document date.
    pub document_date: String,
    /// Mailing date (`YYYY-MM`).
    pub mailing_date: String,
    /// Disposition.
    pub disposition: String,
    /// Previous revision's paper id, or empty.
    pub previous_version: String,
    /// Staged source file path, or empty.
    pub source_file: String,
    /// Converted Markdown path, or empty.
    pub markdown_path: String,
    /// Deprecated dissect artifact path, or empty.
    pub dissect_path: String,
    /// Agora artifact path, or empty.
    pub agora_path: String,
    /// Assay report path, or empty.
    pub assay_path: String,
    /// Time of the last citation extraction, or empty.
    pub citations_extracted_at: String,
    /// Last recorded pipeline error, or empty.
    pub error: String,
    /// Line count of the converted Markdown.
    pub line_count: u64,
    /// Pipeline status code.
    pub status: i64,
}

